const LOCAL_STORAGE_KEY = 'agri_pulse_banking_loans_db';
const LOCAL_CONFIG_KEY = 'agri_pulse_banking_db_config';

export function loadBankingLoans(): AgriLoanDisbursement[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Error reading banking loans from localStorage:', err);
  }
  // Store default
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(INITIAL_LOAN_RECORDS));
  } catch {}
  return INITIAL_LOAN_RECORDS;
}

export function saveBankingLoans(loans: AgriLoanDisbursement[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(loans));
  } catch (err) {
    console.error('Error saving banking loans to localStorage:', err);
  }
}

export function loadBankingConfig(): BankingDatabaseConfig {
  try {
    const raw = localStorage.getItem(LOCAL_CONFIG_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (err) {
    console.error('Error reading banking config:', err);
  }
  return INITIAL_BANKING_CONFIG;
}

export function saveBankingConfig(config: BankingDatabaseConfig): void {
  try {
    localStorage.setItem(LOCAL_CONFIG_KEY, JSON.stringify(config));
  } catch (err) {
    console.error('Error saving banking config:', err);
  }
}

export function resetBankingDatabase(): AgriLoanDisbursement[] {
  try {
    localStorage.removeItem(LOCAL_STORAGE_KEY);
  } catch {}
  return INITIAL_LOAN_RECORDS;
}

